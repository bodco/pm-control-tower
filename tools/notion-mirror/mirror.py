TRANSCRIPT_RE = re.compile(r"<transcript>(.*?)</transcript>", re.S)


def transcript_state(md):
    """None: no transcript block; 'omitted': placeholder only; 'included': real transcript text."""
    m = TRANSCRIPT_RE.search(md or "")
    if not m:
        return None
    inner = m.group(1).strip()
    if not inner or inner.lower().startswith("transcript omitted"):
        return "omitted"
    return "included"


def now_utc():
    return datetime.now(timezone.utc)


def iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%S.000Z")


def now_local_iso():
    # ISO 8601 with the local UTC offset, e.g. 2026-10-18T09:07:03+03:00
    return datetime.now().astimezone().isoformat(timespec="seconds")


def log(msg):
    os.makedirs(LOG_DIR, exist_ok=True)
    line = "%s %s" % (now_local_iso(), msg)
    print(line, flush=True)
    try:
        if os.path.exists(LOG_PATH) and os.path.getsize(LOG_PATH) > 2_000_000:
            os.replace(LOG_PATH, LOG_PATH + ".1")
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except OSError:
        pass


def norm_id(s):
    if not s:
        return None
    m = re.findall(r"[0-9a-fA-F]{32}|[0-9a-fA-F-]{36}", s)
    if not m:
        return None
    h = m[-1].replace("-", "").lower()
    if len(h) != 32:
        return None
    return "%s-%s-%s-%s-%s" % (h[:8], h[8:12], h[12:16], h[16:20], h[20:])


def safe_name(s, limit=90):
    s = (s or "").strip()
    s = re.sub(r"[\\/:*?\"<>|\x00-\x1f]", " ", s)
    s = re.sub(r"\s+", " ", s).strip(" .")
    while len(s) > limit or len(s.encode("utf-8")) > 160:
        s = s[:-1]
    s = s.rstrip(" .")
    return s or "Untitled"


def folder_name(title):
    # Strip leading emoji/symbols ("🏠 Home" -> "Home").
    t = re.sub(r"^[^\w]+", "", title or "", flags=re.UNICODE)
    return safe_name(t or title)


def read_secret(path, var):
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if line.startswith("export "):
                line = line[7:].strip()
            if line.startswith(var + "="):
                val = line[len(var) + 1:].strip()
                if len(val) >= 2 and val[0] == val[-1] and val[0] in "'\"":
                    val = val[1:-1]
                return val
    raise SystemExit("Secret variable %s not found in the secrets file" % var)


def get_token(cfg):
    if os.environ.get("NOTION_TOKEN"):
        return os.environ["NOTION_TOKEN"]
    if cfg.get("secrets_file") and cfg.get("token_env"):
        return read_secret(cfg["secrets_file"], cfg["token_env"])
    raise SystemExit("No Notion token: set NOTION_TOKEN or secrets_file + token_env in the config")


# Control Tower database names (the Notion template) -> config keys.
DB_NAMES = {"tasks": ["tasks tracker", "tasks"], "threads": ["threads"], "meetings": ["meetings"],
            "topics": ["topics"], "knowledge": ["knowledge base", "knowledge"], "risks": ["risks"],
            "decisions": ["decisions"], "reports": ["reports"], "projects": ["projects"]}


def discover(cfg):
    """Finds the Control Tower data sources the integration can see (by title) and writes them to the
    config. Several matches for one name (for example the public template and a working copy both
    shared with the integration): the most recently edited one wins, and all are listed."""
    api = Notion(get_token(cfg), cfg.get("notion_version", "2025-09-03"), cfg.get("markdown_version"), 0.34)
    out = pick_latest(visible_sources(api))
    if "projects" not in out:
        raise SystemExit("No Projects database visible to this integration: share the Control Tower page with it")
    cfg["projects_ds"] = out.pop("projects")
    cfg["databases"] = out
    atomic_write(CONFIG_PATH, json.dumps(cfg, ensure_ascii=False, indent=1) + "\n")
    print("discovered: " + ", ".join(sorted(out)) + " + projects")
    missing = sorted(set(DB_NAMES) - set(out) - {"projects"})
    if missing:
        print("not found (not shared with the integration?): " + ", ".join(missing))
    return 0


def visible_sources(api):
    """config key -> [(last_edited, id, name)] for every data source whose title is a Control Tower name."""
    found, cursor = {}, None
    while True:
        body = {"filter": {"property": "object", "value": "data_source"}, "page_size": 100}
        if cursor:
            body["start_cursor"] = cursor
        r = api.req("POST", "/search", body)
        for ds in r.get("results", []):
            name = re.sub(r"[^\w ]", "", rich(ds.get("title") or [])).strip().lower()
            for key in (k for k, names in DB_NAMES.items() if name in names):
                found.setdefault(key, []).append((ds.get("last_edited_time") or "", ds["id"], name))
        if not r.get("has_more"):
            return found
        cursor = r.get("next_cursor")


def pick_latest(found):
    out = {}
    for key, hits in found.items():
        hits.sort(reverse=True)
        out[key] = hits[0][1]
        if len(hits) > 1:
            print("note: %d data sources named %r, using the most recently edited one" % (len(hits), hits[0][2]))
    return out


def atomic_write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


