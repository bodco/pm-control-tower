ORPHAN_SKIP = {"INDEX.md", "MIRROR_STATUS.md", "project.md", "current-state.md",
               "workspace.md", ".gitignore"}


def _nkey(p):
    import unicodedata
    return unicodedata.normalize("NFC", os.path.normpath(p))


def _free_path(dst):
    if not os.path.exists(dst):
        return dst
    root, ext = os.path.splitext(dst)
    i = 2
    while os.path.exists("%s (%d)%s" % (root, i, ext)):
        i += 1
    return "%s (%d)%s" % (root, i, ext)


def move_file(src, dst, touch=False):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    dst = _free_path(dst)
    try:
        os.replace(src, dst)
    except OSError:
        shutil.move(src, dst)
    if touch:  # the retention clock starts when the file lands in _archived
        os.utime(dst, None)
    return dst


def mirror_files(top):
    """*.md files under a _notion/ tree, outside _archived/, except the mirror's own files."""
    for d, dirs, files in os.walk(top):
        dirs[:] = [x for x in dirs if x != "_archived"]
        for fn in files:
            if fn.endswith(".md") and fn not in ORPHAN_SKIP:
                yield os.path.join(d, fn)


def find_orphans(roots, known_paths):
    """(tree_top, path) for *.md under <root>/_notion/ that state does not reference."""
    known = set(_nkey(p) for p in known_paths if p)
    out = []
    for root in roots:
        top = os.path.join(root, MIRROR_DIR)
        if os.path.isdir(top):
            out += [(top, p) for p in mirror_files(top) if _nkey(p) not in known]
    return out


def archive_orphans(roots, known_paths):
    moved = []
    for top, p in find_orphans(roots, known_paths):
        dst = move_file(p, os.path.join(top, "_archived", os.path.relpath(p, top)), touch=True)
        moved.append(dst)
    return moved


def sweep_archived(roots, work_root, days, day_str):
    """Move files older than `days` from any _archived/ to <work>/_to_delete/... (never deletes)."""
    cutoff = time.time() - days * 86400
    dest_root = os.path.join(work_root, "_to_delete", "notion-mirror-archived-" + day_str)
    moved = []
    for root in roots:
        arch = os.path.join(root, MIRROR_DIR, "_archived")
        if not os.path.isdir(arch):
            continue
        for d, _dirs, files in os.walk(arch):
            for fn in files:
                p = os.path.join(d, fn)
                try:
                    if os.path.getmtime(p) >= cutoff:
                        continue
                except OSError:
                    continue
                ap = os.path.abspath(p)
                wr = os.path.abspath(work_root)
                rel = os.path.relpath(ap, wr) if ap.startswith(wr + os.sep) else ap.lstrip(os.sep)
                moved.append(move_file(p, os.path.join(dest_root, rel)))
    return moved


# ---------------------------------------------------------------- render

def render(page, db_key, rs, body, truncated, extra=None, head_extra=None):
    if not isinstance(rs, Resolver):
        rs = Resolver(rs)
    head = front_matter(page, db_key, rs, truncated, head_extra)
    head += ["---", "<!-- %s -->" % GENERATED_NOTE, "", "# " + title_of(page), "", rs.text(body or "")]
    for t, md in extra or []:
        head += ["", "---", "", "## [child page] " + t, "", rs.text(md)]
    return "\n".join(head).rstrip() + "\n"


def front_matter(page, db_key, rs, truncated, head_extra):
    head = ["---",
            "title: %s" % json.dumps(title_of(page), ensure_ascii=False),
            "notion_id: %s" % norm_id(page["id"]),
            "url: %s" % page.get("url", ""),
            "db: %s" % db_key,
            "created: %s" % page.get("created_time", ""),
            "last_edited: %s" % page.get("last_edited_time", ""),
            "mirrored: %s" % iso(now_utc())]
    if truncated:
        # The markdown export skipped blocks it cannot render (files, embeds, AI blocks);
        # we keep what came back and do not fall back to the (expensive) blocks API.
        head += ["truncated: true", "truncated_reason: unsupported_blocks"]
    head += list(head_extra or []) + ["properties:"]
    for name, p in (page.get("properties") or {}).items():
        val = prop_value(p, rs.titles, rs.users)
        if val not in (None, "", []):
            head.append("  %s: %s" % (json.dumps(name, ensure_ascii=False), json.dumps(val, ensure_ascii=False)))
    return head


